//! The runtime of `concurrent!` (spec.md 5.3): one worker runs its processes one step at a time, by
//! the rules Start, End, Done and Fail of sched.rs. It is backend-independent: every backend offers
//! the same `Backend` calls, and this file is the only place the rules are applied.
//!
//! The processes are static. `concurrent!` generates a `Set` whose methods dispatch on the index of
//! a process, and each process's `Process` impl (from `#[trame::process]`) calls its own `step`. No
//! trait object and no function pointer reaches a step.

use crate::backend::{Backend, Selected};
use crate::cells::{Cells, Tags};
use crate::sched::{self, Proc, St};
use crate::status::{Status, Waits};
use crate::time;
use alloc::format;
use alloc::string::String;
use alloc::vec::Vec;
use core::any::TypeId;

/// The most processes one `concurrent!` runs: sched.rs keeps per-process conditions in 64-bit masks.
pub const MAX_PROCESSES: usize = 64;

/// One process: its cells, and one step. Implemented by `#[trame::process]`.
pub trait Process {
    /// What a step fails with. Every process of one `concurrent!` has the same `Error`.
    type Error;
    /// The number of cell parameters of `step`.
    const ARITY: usize;
    /// Whether `step` takes a cell of type `ty`.
    fn takes(ty: TypeId) -> bool;
    /// Whether a frame of some type this process owns is available to this worker.
    fn frame_offered() -> bool;
    /// The message types this process owns, each with its name. No tag may have two owners.
    fn tags() -> Tags;
    /// Run one step with the cells it takes. The step's owned types are set for its duration.
    fn run(&mut self, cells: &mut Cells<'_, '_>) -> Result<Status, Self::Error>;
}

/// The processes of one `concurrent!`, in priority order. Generated by `concurrent!`, which
/// dispatches on the index with a `match`.
pub trait Set {
    type Error;
    const LEN: usize;
    /// The type name of process `i`, for messages.
    fn name(i: usize) -> &'static str;
    /// Whether process `i` takes a cell of type `ty`.
    fn takes(i: usize, ty: TypeId) -> bool;
    /// The number of cell parameters of process `i`.
    fn arity(i: usize) -> usize;
    /// Whether a frame of some type process `i` owns is available.
    fn frame_offered(i: usize) -> bool;
    /// The message types process `i` owns.
    fn tags(i: usize) -> Tags;
    /// One step of process `i`.
    fn run(&mut self, i: usize, cells: &mut Cells<'_, '_>) -> Result<Status, Self::Error>;
}

/// Whether a frame of type `ty` is available to this worker. Used by `Process::frame_offered`.
pub fn offered(ty: TypeId) -> bool {
    Selected::worker_offer(ty)
}

/// The processes whose step takes a cell of type `t`, by name, for a message.
fn takers<S: Set>(t: TypeId) -> String {
    let names: Vec<String> = (0..S::LEN).filter(|&i| S::takes(i, t)).map(|i| format!("`{}`", S::name(i))).collect();
    names.join(", ")
}

/// Abort unless the `concurrent!`'s cells and processes match: no two cells of one type, no cell that
/// no step takes, no step parameter without a cell, and no message type with two owners (spec.md 3,
/// Tag ownership). Runs once, before any step.
fn check<S: Set>(cells: &Cells<'_, '_>) {
    let types = cells.types();
    assert!(types.len() <= 64, "trame: concurrent! takes at most 64 cells, it has {}", types.len());
    for (k, (t, name)) in types.iter().enumerate() {
        if types[..k].iter().any(|(u, _)| u == t) {
            panic!(
                "trame: concurrent!: two cells have the type `{name}`, and the processes {} take that type; a step's \
                 parameters are matched to cells by type, so wrap one cell in a type of your own, e.g. struct Pending(Vec<Job>)",
                takers::<S>(*t)
            );
        }
        if !(0..S::LEN).any(|i| S::takes(i, *t)) {
            panic!("trame: concurrent!: the cell of type `{name}` is taken by no process's step; remove it from concurrent!");
        }
    }
    for i in 0..S::LEN {
        for j in i + 1..S::LEN {
            for (t, name) in S::tags(i).iter().flatten() {
                if S::tags(j).iter().flatten().any(|(u, _)| u == t) {
                    panic!(
                        "trame: concurrent!: message type `{name}` is owned by processes `{}` and `{}`; a tag has one owner in a \
                         concurrent! (spec.md 3). Fix: give one of them another message type",
                        S::name(i),
                        S::name(j)
                    );
                }
            }
        }
    }
    for i in 0..S::LEN {
        let found = types.iter().filter(|(t, _)| S::takes(i, *t)).count();
        assert!(
            found == S::arity(i),
            "trame: concurrent!: process `{}` has {} cell parameters but {found} of them have a cell; \
             add a cell of each parameter's type to concurrent!",
            S::name(i),
            S::arity(i),
        );
    }
}

/// The bit of process `i` in a mask.
fn bit(i: usize) -> u64 {
    1 << i
}

/// Run the processes of one `concurrent!` until every one is done (Ok) or one has failed and none is
/// running (Err with its error). Steps run on this thread, one at a time. Nothing allocates.
pub fn concurrent<S: Set>(set: &mut S, cells: &mut Cells<'_, '_>) -> Result<(), S::Error> {
    let n = S::LEN;
    assert!(n <= MAX_PROCESSES, "trame: concurrent! runs at most {MAX_PROCESSES} processes, it has {n}");
    check::<S>(cells);
    let clock = time::now().clock();
    let mut ps = [Proc { cells: 0, st: St::Fresh, d: false, running: false }; MAX_PROCESSES];
    let mut waits = [Waits::default(); MAX_PROCESSES];
    for (i, p) in ps.iter_mut().enumerate().take(n) {
        for (k, (t, _)) in cells.types().iter().enumerate() {
            if S::takes(i, *t) {
                p.cells |= bit(k);
            }
        }
    }
    let mut held = 0_u64;
    let mut failed: Option<S::Error> = None;
    loop {
        // Read before the conditions: an act after this read wakes the idle below, not lost.
        let epoch = Selected::worker_epoch();
        let ps = &mut ps[..n];
        let now = conditions::<S>(ps, &waits[..n]);
        match sched::start(ps, held, &now) {
            Some(i) => {
                ps[i].running = true;
                held |= ps[i].cells;
                let s = match set.run(i, cells) {
                    Ok(Status::Progress) => St::Progress,
                    Ok(Status::Done) => St::Done,
                    Ok(Status::Wait(w)) => {
                        if let Some(at) = w.deadline() {
                            assert!(
                                at.clock() == clock,
                                "trame: .until was given a reading of another clock; a worker waits only on its own clock"
                            );
                        }
                        waits[i] = w;
                        St::Wait {
                            frame: w.frame_wanted(),
                            room: w.room_mask() != 0,
                            until: w.deadline().is_some(),
                            cells: w.is_empty(),
                        }
                    }
                    Err(e) => {
                        failed = Some(e);
                        St::Err
                    }
                };
                sched::end(ps, i, s, &mut held);
            }
            None => match sched::answer(ps) {
                Some(Ok(())) => return Ok(()),
                Some(Err(_)) => return Err(failed.take().expect("a failed process recorded its error")),
                None => Selected::worker_idle(next_deadline(ps, &waits[..n]), epoch),
            },
        }
    }
}

/// Whether some outgoing route in `mask` (bit k is route k, see `Backend::worker_route`) has room. A
/// wait on several rooms holds when any does, so the mask collapses to one bit for sched.rs.
fn room_holds(mask: u64) -> bool {
    (0..64).any(|k| mask >> k & 1 == 1 && Selected::worker_room(k))
}

/// The conditions Ω that hold now, as bitmasks over the processes (sched::Now). A process's wait
/// condition is read only for a process that waits on it, so a wait's check runs only then. A clock
/// is read only for a process that waits on a deadline: reading it yields the baton.
fn conditions<S: Set>(ps: &[Proc], waits: &[Waits]) -> sched::Now {
    let mut out = sched::Now { frame: 0, room: 0, until: 0 };
    for (i, (p, w)) in ps.iter().zip(waits).enumerate() {
        if !matches!(p.st, St::Wait { .. }) {
            continue;
        }
        if w.frame_wanted() {
            out.frame |= bit(i) * u64::from(S::frame_offered(i));
        }
        if w.room_mask() != 0 {
            out.room |= bit(i) * u64::from(room_holds(w.room_mask()));
        }
        if let Some(at) = w.deadline() {
            out.until |= bit(i) * u64::from(time::now().at() >= at.at());
        }
    }
    out
}

/// The earliest deadline of a process waiting on the clock, or None when none waits on it.
fn next_deadline(ps: &[Proc], waits: &[Waits]) -> Option<u64> {
    ps.iter()
        .zip(waits)
        .filter(|(p, _)| matches!(p.st, St::Wait { until: true, .. }))
        .filter_map(|(_, w)| w.deadline())
        .map(|at| u64::try_from(at.at().as_nanos()).unwrap_or(u64::MAX))
        .min()
}
