// Traffic sweep over eight patterns and the linked backend.
// Each rank generates and drains frames concurrently.
//
//     mpirun -n 4 traffic [frames_per_rank] [pattern]
//
// Patterns vary destination, frame size, burst length, route length, and reply dependency. They
// measure throughput, locality, message rate, buffering, route churn, and dependent latency.
// Frames use `post`, and `hotspot` concentrates four fifths of bytes on one tenth of the ranks.

use std::time::Instant;

#[path = "wire.rs"]
mod wire;
use wire::*;

/// One-way data traffic.
const DATA: Tag = 0;
/// A request whose sender waits for a response.
const REQ: Tag = 1;
/// Response to a request.
const RESP: Tag = 2;
/// End of a rank's generation.
const SETTLED: Tag = 3;
/// A rank's counters for rank 0.
const REPORT: Tag = 4;
/// Releases ranks after rank 0 counts a pattern.
const GO: Tag = 5;

/// Largest frame any pattern draws.
const CAP: usize = 65536;

/// Frame destination policy.
#[derive(Clone, Copy)]
enum Dest {
    /// Any peer, redrawn after the route length.
    Any,
    /// One of the two neighboring ranks.
    Near,
    /// Four frames in five at the first tenth of ranks.
    Hot,
}

/// Traffic pattern parameters.
struct Pattern {
    name: &'static str,
    dest: Dest,
    /// Frame size in bytes, drawn uniformly from this range.
    size: (usize, usize),
    /// Frames sent back to back before draining. 1 is a steady stream.
    burst: usize,
    /// Frames sent to one destination before drawing another. 1 redraws every frame.
    route: usize,
    /// Whether the sender waits for a response before generating the next frame.
    reply: bool,
    /// Fraction of the run budget assigned to this pattern.
    share: usize,
}

const PATTERNS: [Pattern; 8] = [
    p("uniform", Dest::Any, (256, 256), 1, 1, false, 1),
    p("neighbor", Dest::Near, (256, 256), 1, 1, false, 1),
    p("hotspot", Dest::Hot, (256, 256), 1, 1, false, 1),
    p("tiny", Dest::Any, (16, 64), 1, 1, false, 1),
    p("bulk", Dest::Any, (4096, CAP), 1, 1, false, 64),
    p("bursty", Dest::Any, (256, 256), 64, 1, false, 1),
    p("churn", Dest::Any, (256, 256), 1, 512, false, 1),
    p("pair", Dest::Any, (256, 256), 1, 1, true, 16),
];

const fn p(
    name: &'static str,
    dest: Dest,
    size: (usize, usize),
    burst: usize,
    route: usize,
    reply: bool,
    share: usize,
) -> Pattern {
    Pattern {
        name,
        dest,
        size,
        burst,
        route,
        reply,
        share,
    }
}

/// Deterministic per rank for reproducible traffic.
struct Rng(u64);

impl Rng {
    fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_mul(6364136223846793005).wrapping_add(1);
        self.0 >> 11
    }

    /// Uniform on `[0, n)`.
    fn below(&mut self, n: usize) -> usize {
        (self.next() % n.max(1) as u64) as usize
    }

    /// Uniform on `[lo, hi]`.
    fn between(&mut self, lo: usize, hi: usize) -> usize {
        lo + self.below(hi - lo + 1)
    }
}

/// What every pattern needs and none of them changes.
struct World {
    me: Rank,
    ranks: usize,
    peers: Vec<Rank>,
    /// Zero padding used to slice frames. Contents are not measured.
    pad: Vec<u8>,
    rng: Rng,
}

impl World {
    /// Peer destination, never this rank.
    fn draw(&mut self, dest: Dest) -> Rank {
        let (me, ranks) = (self.me, self.ranks);
        let pick = match dest {
            Dest::Any => self.rng.below(ranks) as Rank,
            // Choose either neighbor with wraparound.
            Dest::Near => match self.rng.below(2) {
                0 => (me + 1) % ranks as Rank,
                _ => (me + ranks as Rank - 1) % ranks as Rank,
            },
            // Send four fifths to the first tenth, including at least one rank.
            Dest::Hot => match self.rng.below(5) {
                0 => self.rng.below(ranks) as Rank,
                _ => self.rng.below(ranks.div_ceil(10)) as Rank,
            },
        };
        // Replace self-destination with the next rank to avoid loopback traffic.
        match pick == me {
            true => (me + 1) % ranks as Rank,
            false => pick,
        }
    }
}

/// Eight counters reported by one rank for one pattern.
const FIELDS: usize = 8;

fn pack(vals: [u64; FIELDS]) -> Vec<u8> {
    vals.iter().flat_map(|v| v.to_le_bytes()).collect()
}

fn unpack(bytes: &[u8]) -> [u64; FIELDS] {
    std::array::from_fn(|i| u64::from_le_bytes(bytes[i * 8..i * 8 + 8].try_into().unwrap()))
}

/// Everything one rank counts while a pattern runs.
#[derive(Default)]
struct Tally {
    /// Frames generated by this rank.
    made: u64,
    /// Frames sent, including responses.
    posted: u64,
    bytes: u64,
    /// Frames received. The global total must equal `posted`.
    got: u64,
    /// Responses received by waiting senders.
    answers: u64,
    /// Round-trip times for the reply pattern.
    waits: Vec<u64>,
}

/// Drain one frame and answer requests. Ranks keep draining after reaching their quota so peers
/// waiting for responses can progress.
fn drain(
    wire: &mut Wire,
    t: &mut Tally,
    marks: &mut usize,
    reports: &mut Vec<[u64; FIELDS]>,
    pad: &[u8],
) -> bool {
    match wire.poll() {
        Some((from, REQ, data)) => {
            t.got += 1;
            wire.post(from, RESP, &pad[..data.len()]);
            t.posted += 1;
            t.bytes += data.len() as u64;
        }
        Some((_, RESP, _)) => {
            t.got += 1;
            t.answers += 1;
        }
        Some((_, DATA, _)) => t.got += 1,
        Some((_, SETTLED, _)) => *marks += 1,
        // A settled peer may already be reporting.
        Some((_, REPORT, data)) => reports.push(unpack(&data)),
        Some((from, tag, _)) => eprintln!("rank {from} sent an unknown tag {tag}"),
        None => return false,
    }
    true
}

/// Run one pattern to its quota, then wait until every peer has finished theirs.
fn run(
    wire: &mut Wire,
    pat: &Pattern,
    quota: usize,
    w: &mut World,
    reports: &mut Vec<[u64; FIELDS]>,
) -> (Tally, f64) {
    let mut t = Tally::default();
    let mut marks = 1;
    let (mut dest, mut held) = (w.draw(pat.dest), pat.route);

    let started = Instant::now();
    while (t.made as usize) < quota {
        for _ in 0..pat.burst {
            if (t.made as usize) >= quota {
                break;
            }
            if held == 0 {
                dest = w.draw(pat.dest);
                held = pat.route;
            }
            held -= 1;
            let n = w.rng.between(pat.size.0, pat.size.1);

            match pat.reply {
                false => wire.post(dest, DATA, &w.pad[..n]),
                true => {
                    let asked = Instant::now();
                    wire.post(dest, REQ, &w.pad[..n]);
                    // Only one local request is outstanding. Other requests are served meanwhile.
                    let want = t.answers + 1;
                    while t.answers < want {
                        drain(wire, &mut t, &mut marks, reports, &w.pad);
                    }
                    t.waits.push(asked.elapsed().as_nanos() as u64);
                }
            }
            t.made += 1;
            t.posted += 1;
            t.bytes += n as u64;
        }
        while drain(wire, &mut t, &mut marks, reports, &w.pad) {}
    }
    let elapsed = started.elapsed().as_secs_f64();

    // A peer's mark follows its last frame, so all marked peers have drained.
    wire.broadcast(&w.peers, SETTLED, &[]);
    while marks < w.ranks {
        drain(wire, &mut t, &mut marks, reports, &w.pad);
    }
    (t, elapsed)
}

/// Mean and 99th percentile of round trips in nanoseconds.
fn waits(mut samples: Vec<u64>) -> (u64, u64) {
    if samples.is_empty() {
        return (0, 0);
    }
    samples.sort_unstable();
    let mean = samples.iter().sum::<u64>() / samples.len() as u64;
    (mean, samples[samples.len() * 99 / 100])
}

fn main() {
    let mut wire = Wire::start();
    let (me, ranks) = (wire.rank(), wire.size() as usize);
    if ranks < 2 {
        eprintln!("traffic needs at least 2 ranks");
        wire.done();
        return;
    }

    let mut args = std::env::args().skip(1);
    let budget: usize = args.next().and_then(|a| a.parse().ok()).unwrap_or(20000);
    let only = args.next();

    let mut w = World {
        me,
        ranks,
        peers: (0..ranks as Rank).filter(|&r| r != me).collect(),
        pad: vec![0u8; CAP],
        rng: Rng(0x9e3779b9 ^ me as u64),
    };

    if me == 0 {
        println!("pattern\tranks\tframes\tMB\ts\tkframe/s\tMB/s\tmean_us\tp99_us");
    }
    for pat in &PATTERNS {
        if only.as_deref().is_some_and(|name| name != pat.name) {
            continue;
        }
        let mut reports = Vec::new();
        let (t, elapsed) = run(
            &mut wire,
            pat,
            (budget / pat.share).max(1),
            &mut w,
            &mut reports,
        );
        let (mean, p99) = waits(t.waits);
        let row = [
            me as u64,
            t.made,
            t.posted,
            t.bytes,
            t.got,
            (elapsed * 1e9) as u64,
            mean,
            p99,
        ];

        // Rank 0 releases the next pattern after gathering all reports.
        match me {
            0 => {
                reports.push(row);
                while reports.len() < ranks {
                    if let Some((_, REPORT, data)) = wire.poll() {
                        reports.push(unpack(&data));
                    }
                }
                report(pat, ranks, &reports);
                wire.broadcast(&w.peers, GO, &[]);
            }
            _ => {
                wire.post(0, REPORT, &pack(row));
                // Held, not dropped: a peer released earlier may already be sending the next pattern.
                wire.take(GO);
            }
        }
    }
    wire.done();
    return;
}

/// Report one pattern summed across ranks. Rates use the slowest rank because quotas run
/// concurrently.
fn report(pat: &Pattern, ranks: usize, reports: &[[u64; FIELDS]]) {
    let sum = |i: usize| reports.iter().map(|r| r[i]).sum::<u64>();
    let (made, posted, bytes, got) = (sum(1), sum(2), sum(3), sum(4));
    let secs = reports.iter().map(|r| r[5]).max().unwrap_or(0) as f64 / 1e9;
    let mb = bytes as f64 / (1 << 20) as f64;

    let latency = match pat.reply {
        true => format!(
            "\t{:.1}\t{:.1}",
            sum(6) as f64 / ranks as f64 / 1e3,
            reports.iter().map(|r| r[7]).max().unwrap_or(0) as f64 / 1e3
        ),
        false => "\t-\t-".to_string(),
    };
    println!(
        "{}\t{ranks}\t{made}\t{mb:.1}\t{secs:.3}\t{:.1}\t{:.1}{latency}",
        pat.name,
        made as f64 / secs / 1e3,
        mb / secs,
    );
    // These patterns use no lossy lane, so a completed run with unequal counts is a failed
    // reliable-message experiment, not another measurement row.
    assert_eq!(got, posted, "{} lost reliable message frames", pat.name);
}
